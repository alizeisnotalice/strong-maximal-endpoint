#!/usr/bin/env bash
# Reproducibility check for the Lean development.
#
#   ./verify.sh
#
# 1. refuses to run if any source contains `sorry`, `admit`, or a project axiom;
# 2. regenerates `StrongMaximal/Audit.lean` by scanning **every** declaration in
#    `StrongMaximal/*.lean` (so the audit cannot drift from the sources);
# 3. compiles every module from scratch and runs the audit;
# 4. fails unless every declaration depends only on `propext`, `Classical.choice`,
#    `Quot.sound`.
set -euo pipefail
cd "$(dirname "$0")"
export PATH="$HOME/.elan/bin:$PATH"

if [ ! -d .lake/packages/mathlib ]; then
  echo "Mathlib is not available in .lake/packages."
  echo "On a fresh checkout run:  lake exe cache get   (uses ./lake-manifest.json)"
  exit 1
fi

echo "== pins"
cat lean-toolchain
grep -o '"rev": "[0-9a-f]*"' lake-manifest.json | head -3

echo "== forbidden tokens"
if grep -rn --include='*.lean' -E '(^|[^A-Za-z_])(sorry|admit)([^A-Za-z_]|$)' \
     StrongMaximal/ StrongMaximal.lean ; then
  echo "FAIL: source contains sorry/admit"; exit 1
fi
if grep -rn --include='*.lean' -E '^[[:space:]]*axiom ' StrongMaximal/ StrongMaximal.lean ; then
  echo "FAIL: source declares an axiom"; exit 1
fi
echo "none"

echo "== regenerating StrongMaximal/Audit.lean"
python3 - <<'PY'
import re, pathlib
root = pathlib.Path('.')
decl = re.compile(r'^(?:noncomputable\s+)?(?:private\s+)?(theorem|lemma|def|abbrev)\s+([A-Za-z_][A-Za-z0-9_\'.]*)')
names = []
for path in sorted(root.glob('StrongMaximal/*.lean')):
    if path.name == 'Audit.lean':
        continue
    stack = []
    for line in path.read_text().splitlines():
        s = line.strip()
        m = re.match(r'^namespace\s+([A-Za-z_][A-Za-z0-9_\'.]*)', s)
        if m:
            stack.append(m.group(1)); continue
        if re.match(r'^end(\s|$)', s) and stack:
            stack.pop(); continue
        m = decl.match(s)
        if m:
            names.append('.'.join(stack + [m.group(2)]))
seen, uniq = set(), []
for n in names:
    if n not in seen:
        seen.add(n); uniq.append(n)
body = ["/-", "Axiom audit.  GENERATED by `verify.sh` by scanning every declaration in",
        "`StrongMaximal/*.lean`; do not edit by hand.  Every line must report a subset of",
        "`{propext, Classical.choice, Quot.sound}`.", "-/", "import StrongMaximal", "",
        "open StrongMaximalEndpoint", ""]
body += [f"#print axioms {n}" for n in uniq]
pathlib.Path('StrongMaximal/Audit.lean').write_text("\n".join(body) + "\n")
print(f"  {len(uniq)} declarations")
PY

echo "== clean build"
rm -rf .lake/build/lib/lean/StrongMaximal .lake/build/lib/lean/StrongMaximal.olean
./build.sh > /tmp/verify-build.log 2>&1 || { tail -20 /tmp/verify-build.log; echo "FAIL: build"; exit 1; }
echo "  modules: $(grep -c compiling /tmp/verify-build.log), errors: $(grep -c 'error' /tmp/verify-build.log || true)"

echo "== axiom check"
total=$(grep -c 'depends on axioms' /tmp/verify-build.log || true)
bad=$( { grep 'depends on axioms' /tmp/verify-build.log || true; } \
      | { grep -v 'propext, Classical.choice, Quot.sound' || true; } | wc -l | tr -d ' ')
echo "  audited: $total, non-standard: $bad"
if [ "$bad" != "0" ]; then
  grep 'depends on axioms' /tmp/verify-build.log | grep -v 'propext, Classical.choice, Quot.sound'
  echo "FAIL: non-standard axioms"; exit 1
fi
echo "OK"
